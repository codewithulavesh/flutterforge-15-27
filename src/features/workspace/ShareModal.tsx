import { useState } from 'react';
import { Copy, ExternalLink, Share2, Loader2, CheckCircle2, Github, AlertCircle } from 'lucide-react';
import { Modal } from '@/components/ui/Modal';
import { Button } from '@/components/ui/Button';
import { toast } from '@/components/ui/Toast';

interface ShareModalProps {
  open: boolean;
  onClose: () => void;
  projectName: string;
  files: Array<{ path: string; content: string | null; is_directory?: boolean }>;
}

interface GistFile {
  content: string;
}

async function createAnonymousGist(
  projectName: string,
  files: Array<{ path: string; content: string | null; is_directory?: boolean }>
): Promise<{ id: string; html_url: string }> {
  const dartFiles = files.filter(
    (f): f is { path: string; content: string; is_directory?: boolean } =>
      Boolean(!f.is_directory && f.path.endsWith('.dart') && f.content)
  );

  if (dartFiles.length === 0) throw new Error('No Dart files found to share');

  const mainFile =
    dartFiles.find((f) => f.path === 'lib/main.dart') ??
    dartFiles[0];

  const gistFiles: Record<string, GistFile> = {
    'main.dart': { content: mainFile.content },
  };

  const pubspec = files.find((f) => f.path === 'pubspec.yaml' && f.content);
  if (pubspec?.content) {
    gistFiles['pubspec.yaml'] = { content: pubspec.content };
  }

  const response = await fetch('https://api.github.com/gists', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Accept: 'application/vnd.github.v3+json',
    },
    body: JSON.stringify({
      description: `${projectName} — Generated by FlutterForge`,
      public: true,
      files: gistFiles,
    }),
  });

  if (!response.ok) {
    const err = await response.json().catch(() => ({})) as { message?: string };
    throw new Error(err.message ?? `GitHub API error ${response.status}`);
  }

  const gist = await response.json() as { id: string; html_url: string };
  return gist;
}

export function ShareModal({ open, onClose, projectName, files }: ShareModalProps) {
  const [loading, setLoading] = useState(false);
  const [gistId, setGistId] = useState<string | null>(null);
  const [gistHtmlUrl, setGistHtmlUrl] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [copiedUrl, setCopiedUrl] = useState<string | null>(null);

  const flutterpadBase = (import.meta.env.VITE_FLUTTERPAD_URL || 'https://dartpad.dev').replace(/\/embed.*$/, '');
  const flutterpadUrl = gistId ? `${flutterpadBase}/?id=${gistId}` : null;

  async function handleShare() {
    setLoading(true);
    setError(null);
    try {
      const gist = await createAnonymousGist(projectName, files);
      setGistId(gist.id);
      setGistHtmlUrl(gist.html_url);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to create share link');
    } finally {
      setLoading(false);
    }
  }

  async function handleCopy(url: string) {
    await navigator.clipboard.writeText(url);
    setCopiedUrl(url);
    toast('success', 'Link copied!');
    setTimeout(() => setCopiedUrl(null), 2000);
  }

  function handleClose() {
    setGistId(null);
    setGistHtmlUrl(null);
    setError(null);
    onClose();
  }

  return (
    <Modal onClose={handleClose} open={open} title="Share your Flutter app">
      <div className="space-y-4">
        {!gistId ? (
          <>
            <div className="rounded-xl border border-slate-700 bg-slate-800/50 p-4">
              <div className="flex items-start gap-3">
                <div className="w-10 h-10 rounded-xl bg-cyan-500/10 border border-cyan-500/20 flex items-center justify-center shrink-0">
                  <Share2 size={18} className="text-cyan-400" />
                </div>
                <div>
                  <p className="text-sm font-semibold text-white mb-1">Share via FlutterPad</p>
                  <p className="text-xs text-slate-400 leading-relaxed">
                    Your Flutter code is uploaded to a public GitHub Gist and opened in FlutterPad —
                    anyone with the link can view and run your Flutter widgets instantly, no install needed.
                  </p>
                </div>
              </div>
            </div>

            {error && (
              <div className="flex items-center gap-2 rounded-lg border border-red-500/30 bg-red-500/10 px-3 py-2 text-xs text-red-400">
                <AlertCircle size={13} className="shrink-0" />
                {error}
              </div>
            )}

            <div className="flex gap-2">
              <Button className="flex-1" onClick={() => void handleShare()} disabled={loading} variant="primary">
                {loading ? (
                  <><Loader2 size={14} className="animate-spin mr-2" />Creating share link…</>
                ) : (
                  <><Github size={14} className="mr-2" />Create Share Link</>
                )}
              </Button>
              <Button onClick={handleClose} variant="outline">Cancel</Button>
            </div>

            <p className="text-center text-xs text-slate-500">
              An anonymous public gist will be created on GitHub.
            </p>
          </>
        ) : (
          <>
            <div className="rounded-xl border border-emerald-500/30 bg-emerald-500/10 p-4">
              <div className="flex items-center gap-2 mb-3">
                <CheckCircle2 size={16} className="text-emerald-400 shrink-0" />
                <span className="text-sm font-semibold text-emerald-300">Share link ready!</span>
              </div>

              <div className="space-y-3">
                <div>
                  <p className="text-xs text-slate-400 mb-1.5 font-medium">🎯 FlutterPad — run in browser</p>
                  <div className="flex items-center gap-2 rounded-lg bg-slate-900 border border-slate-700 px-3 py-2">
                    <code className="flex-1 text-xs text-cyan-300 truncate font-mono">{flutterpadUrl}</code>
                    <button
                      onClick={() => flutterpadUrl && void handleCopy(flutterpadUrl)}
                      className="shrink-0 text-slate-400 hover:text-white transition-colors p-1"
                      title="Copy link"
                    >
                      {copiedUrl === flutterpadUrl ? (
                        <CheckCircle2 size={14} className="text-emerald-400" />
                      ) : (
                        <Copy size={14} />
                      )}
                    </button>
                    <a
                      href={flutterpadUrl ?? '#'}
                      target="_blank"
                      rel="noopener noreferrer"
                      className="shrink-0 text-slate-400 hover:text-cyan-400 transition-colors p-1"
                      title="Open in FlutterPad"
                    >
                      <ExternalLink size={14} />
                    </a>
                  </div>
                </div>

                <div>
                  <p className="text-xs text-slate-400 mb-1.5 font-medium">📄 GitHub Gist — source code</p>
                  <div className="flex items-center gap-2 rounded-lg bg-slate-900 border border-slate-700 px-3 py-2">
                    <code className="flex-1 text-xs text-slate-300 truncate font-mono">{gistHtmlUrl}</code>
                    <a
                      href={gistHtmlUrl ?? '#'}
                      target="_blank"
                      rel="noopener noreferrer"
                      className="shrink-0 text-slate-400 hover:text-white transition-colors p-1"
                    >
                      <ExternalLink size={14} />
                    </a>
                  </div>
                </div>
              </div>
            </div>

            <Button className="w-full" onClick={handleClose} variant="outline">Done</Button>
          </>
        )}
      </div>
    </Modal>
  );
}
