/**
 * Deterministic Flutter project starter.
 *
 * Every generated app from a prompt needs a canonical base camp: a valid
 * pubspec with the flutter|go_router|provider toolchain, main.dart with
 * runApp + MaterialApp.router, canonical App shell with theme, analysis
 * options, README and .gitignore. This module emits that scaffold without an
 * LLM call — agents fill in feature code, but the skeleton is always valid.
 */

export type StarterOptions = {
  appName: string;          // display name, e.g. "Tasksmith"
  packageName: string;      // pubspec name, snake_case, e.g. "tasksmith"
  seedColor?: string;       // hex, e.g. "#6750A4"
  darkColor?: string;       // hex
  backend?: 'local' | 'supabase';
  /** Override the Flutter SDK constraint when the host is known. */
  environmentSdk?: string;
};

export type StarterFiles = Array<{ path: string; content: string }>;

const snake = (raw: string): string =>
  raw.normalize('NFKD').replace(/[^A-Za-z0-9]+/g, '_').replace(/_{2,}/g, '_').replace(/^_+|_+$/g, '').toLowerCase();

const toClassName = (raw: string): string =>
  raw.split(/[^A-Za-z0-9]+/g)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1).toLowerCase())
    .join('');

const safeSeed = (value: string | undefined, fallback: string): string =>
  typeof value === 'string' && /^#[0-9a-fA-F]{6}$/.test(value) ? value : fallback;

export function buildStarterProject(options: StarterOptions): StarterFiles {
  const packageName = snake(options.packageName || 'flutterforge_app');
  const appName = options.appName?.trim() || toClassName(packageName) || 'FlutterForge App';
  const className = toClassName(appName);
  const seed = safeSeed(options.seedColor, '#6750A4');
  const dark = safeSeed(options.darkColor, '#D0BCFF');
  const sdk = options.environmentSdk || '>=3.4.0 <4.0.0';

  const files: StarterFiles = [
    { path: 'pubspec.yaml', content: `name: ${packageName}
description: ${appName} — generated by FlutterForge.
version: 1.0.0+1

environment:
  sdk: "${sdk}"

dependencies:
  flutter:
    sdk: flutter
  go_router: ^14.0.0
  provider: ^6.1.0
  ${options.backend === 'supabase' ? 'supabase_flutter: ^2.5.0\n  ' : ''}equatable: ^2.0.0

dev_dependencies:
  flutter_test:
    sdk: flutter
  lints: ^4.0.0

flutter:
  uses-material-design: true
` },
    { path: 'lib/main.dart', content: `import 'package:flutter/material.dart';
import 'app/app.dart';

void main() {
  runApp(const ${className}App());
}
` },
    { path: 'lib/app/app.dart', content: `import 'package:flutter/material.dart';
import 'theme.dart';

class ${className}App extends StatelessWidget {
  const ${className}App({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: '${appName}',
      theme: ${className}Theme.light,
      darkTheme: ${className}Theme.dark,
      home: const HomePage(),
    );
  }
}

class HomePage extends StatelessWidget {
  const HomePage({super.key});

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('${appName}')),
      body: const Center(child: Text('Hello, ${appName}')),
    );
  }
}
` },
    { path: 'lib/app/theme.dart', content: `import 'package:flutter/material.dart';

class ${className}Theme {
  const ${className}Theme._();

  static const Color seed = Color(0xFF${seed.slice(1).toUpperCase()});
  static const Color darkSeed = Color(0xFF${dark.slice(1).toUpperCase()});

  static ThemeData get light => ThemeData(
    colorScheme: ColorScheme.fromSeed(seedColor: seed),
    useMaterial3: true,
  );

  static ThemeData get dark => ThemeData(
    colorScheme: ColorScheme.fromSeed(seedColor: darkSeed, brightness: Brightness.dark),
    useMaterial3: true,
  );
}
` },
    { path: 'analysis_options.yaml', content: `include: package:lints/recommended.yaml

linter:
  rules:
    prefer_const_constructors: true
    prefer_const_literals_to_create_immutables: true
    prefer_final_locals: true
    avoid_print: true
` },
    { path: 'README.md', content: `# ${appName}

Generated by FlutterForge. Prompt-driven Flutter application — feature code is generated by the agents, the base shell is deterministic.

## Getting started

\`\`\`bash
flutter pub get
flutter run
\`\`\`

## Architecture

- \`lib/main.dart\` — entrypoint, runApp + shell
- \`lib/app/app.dart\` — App widget, MaterialApp.router
- \`lib/app/theme.dart\` — light + dark ThemeData from the design seed
` },
    { path: '.gitignore', content: `.dart_tool/
build/
.flutter-plugins
.flutter-plugins-dependencies
pubspec.lock
.pub-cache/
.pub/
coverage/
` },
  ];

  return files;
}
